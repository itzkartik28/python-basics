sgpa=float(input("enter the sgpa:"))

if sgpa>=9.00 and sgpa <=10.00:
    print("grade:O")

elif sgpa>=8.00:
    print("grade:A+")

elif sgpa>=7.00:
    print("grade:A")

elif sgpa>=6.00:
    print("grade:B+")

elif sgpa>=5.50:
    print("grade:B")

elif sgpa>=5.00:
    print("grade:C")

elif sgpa>=4.00:
    print("grade:p")

else:
    print("grade:F")