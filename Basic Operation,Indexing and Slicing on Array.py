import numpy as np

a = np.array([10,20,30,40,50])

# Basic operations
print("Original array:", a)

print("Addition:", a + 10)

print("Subtraction:", a - 5)

print("Multiplication:", a * 2)

print("Division:", a / 2)

# Indexing
print("First element:", a[0])
print("Third element:", a[2])

# Slicing
print("Elements from index 1 to 3:", a[1:4])